VALID_HEIGHTS = {"1", "3", "5", "7.5", "10"}


def normalize_height(raw: str) -> str | None:
    cleaned = raw.replace(",", ".").replace("м", "").replace("m", "").replace("M", "").strip()
    try:
        val = float(cleaned)
    except ValueError:
        return None
    mapping = {1.0: "1", 3.0: "3", 5.0: "5", 7.5: "7.5", 10.0: "10"}
    return mapping.get(val)


def lookup_dd(dive_code: str, position: str, height: str) -> tuple[float | None, str | None]:
    code = dive_code.upper()
    pos = position.upper()

    if code not in DIVE_TABLE:
        return None, f"Прыжок {code} не найден в таблице КТ."

    positions = DIVE_TABLE[code]
    if pos not in positions:
        available = ", ".join(sorted(positions.keys()))
        return None, (
            f"Прыжок {code}: положение {pos} не предусмотрено.\n"
            f"Доступные положения: {available}"
        )

    heights = positions[pos]
    if height not in heights:
        available = ", ".join(sorted(heights.keys(), key=float))
        return None, (
            f"Прыжок {code}{pos}: высота {height} м не предусмотрена.\n"
            f"Доступные высоты: {available} м"
        )

    return heights[height], None


