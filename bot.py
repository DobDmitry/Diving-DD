@dp.message()
async def handle_query(message: Message) -> None:
    text = message.text.strip() if message.text else ""

    # Принимаем: "403 B 7.5", "403B7.5", "403 b 7,5м", "5132D10"
    m = re.match(r"^(\d{3,4})\s*([ABCDabcd])\s*([\d.,]+)\s*[мmMМ]?$", text)
    if not m:
        await message.answer(
            "Неверный формат запроса.\n\n"
            "Используйте: <код> <положение> <высота>\n"
            "Пример: 403 B 7.5"
        )
        return

    dive_code = m.group(1)
    position = m.group(2).upper()
    height = normalize_height(m.group(3))

    if height is None:
        await message.answer(
            "Неверная высота. Доступные значения: 1, 3, 5, 7.5, 10 (метры)."
        )
        return

    dd, error = lookup_dd(dive_code, position, height)
    if error:
        await message.answer(error)
    else:
        await message.answer(f"КТ = {dd}")


